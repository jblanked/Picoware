#!/bin/bash
# Compile test: syntax-checks the pico game engine sources.
set -o pipefail

ENGINE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${ENGINE_DIR}/.." && pwd)"

STANDBY=0
STDIN=0
STUB=0
VERBOSE=0
CC=c++

usage()
{
    echo "Usage: ./compile.sh [options]"
    echo "  -c <file>  Use an existing engine_config.hpp (default: generated stub)"
    echo "  -s         Also build an object file for each source (full compile, not just syntax)"
    echo "  -v         Verbose (print each command as it runs)"
    echo "  -h         Show this help"
    exit 1
}

while getopts "c:shvh" opt; do
    case "$opt" in
        c) STDIN=1; CONFIG_OVERRIDE="$OPTARG" ;;
        s) STUB=1 ;;
        v) VERBOSE=1 ;;
        h) usage ;;
        *) usage ;;
    esac
done

# Default compiler if CXX is set.
[ -n "$CXX" ] && CC="$CXX"
[ -n "$CONFIG_OVERRIDE" ] && CONFIG="${CONFIG_OVERRIDE}"

# Generate a minimal engine_config.hpp (repo root) when none is provided.
if [ -z "$CONFIG" ]; then
    CONFIG="${ROOT_DIR}/engine_config.hpp"
    if [ ! -f "$CONFIG" ]; then
        cat > "$CONFIG" <<'EOF'
#pragma once
// Generated by compile.sh: minimal standalone build config (no-op stubs).

// delay
#define ENGINE_DELAY_INCLUDE <chrono>
#define ENGINE_DELAY_MS(ms) ((void)0)

// memory
#define ENGINE_MEM_INCLUDE <new>
#define ENGINE_MEM_NEW new
#define ENGINE_MEM_DELETE delete
#define ENGINE_MEM_MALLOC(size) malloc(size)
#define ENGINE_MEM_FREE(ptr) free(ptr)
#include <cstdlib>
#include <string.h>

// font
#define ENGINE_FONT_INCLUDE <stdint.h>
#define ENGINE_FONT_SIZE int
#define ENGINE_FONT_DEFAULT 0

// logging
#define ENGINE_LOG_INCLUDE <stdio.h>
#define ENGINE_LOG_INFO(...)

// lcd
#define ENGINE_LCD_INCLUDE <stdint.h>
#define ENGINE_LCD_WIDTH 320
#define ENGINE_LCD_HEIGHT 240
#define ENGINE_LCD_INIT() ((void)0)
#define ENGINE_LCD_DEINIT() ((void)0)
#define ENGINE_LCD_CLEAR(c) ((void)0)
#define ENGINE_LCD_SWAP() ((void)0)
#define ENGINE_LCD_PIXEL(x, y, c) ((void)0)
#define ENGINE_LCD_LINE(x1, y1, x2, y2, c) ((void)0)
#define ENGINE_LCD_RECTANGLE(x, y, w, h, c) ((void)0)
#define ENGINE_LCD_FILL_RECTANGLE(x, y, w, h, c) ((void)0)
#define ENGINE_LCD_CIRCLE(x, y, r, c) ((void)0)
#define ENGINE_LCD_FILL_CIRCLE(x, y, r, c) ((void)0)
#define ENGINE_LCD_TRIANGLE(x1, y1, x2, y2, x3, y3, c) ((void)0)
#define ENGINE_LCD_FILL_TRIANGLE(x1, y1, x2, y2, x3, y3, c) ((void)0)
#define ENGINE_LCD_POLYGON(x, y, n, c) ((void)0)
#define ENGINE_LCD_FILL_POLYGON(x, y, n, c) ((void)0)
#define ENGINE_LCD_BLIT(x, y, w, h, b) ((void)0)
#define ENGINE_LCD_BLIT_16BIT(x, y, w, h, b) ((void)0)
#define ENGINE_LCD_TEXT(x, y, t, c, f) ((void)0)
EOF
        echo "Generated minimal config: ${CONFIG}"
    fi
fi

if [ ! -f "$CONFIG" ]; then
    echo "Config not found: ${CONFIG}" >&2
    exit 1
fi

BASE_OPTS=(-std=c++17 -I"${ENGINE_DIR}" -isystem "$(dirname "$CONFIG")")
[ "$VERBOSE" -eq 1 ] && BASE_OPTS+=(-v)

fail=0
total=0

for f in "${ENGINE_DIR}"/*.cpp; do
    total=$((total + 1))
    if [ "$STUB" -eq 1 ]; then
        out="$(mktemp -d)/$(basename "${f%.cpp}").o"
        cmd=("$CC" "${BASE_OPTS[@]}" -c "$f" -o "$out")
    else
        cmd=("$CC" "${BASE_OPTS[@]}" -fsyntax-only "$f")
    fi

    if ! "${cmd[@]}" 2> /tmp/compile_test_err.txt; then
        cat /tmp/compile_test_err.txt
        echo "FAIL: ${f}"
        fail=$((fail + 1))
        continue
    fi
    echo "PASS: ${f}"
done

echo ""
echo "Checked ${total} source file(s): $((total - fail)) passed, ${fail} failed."
[ "$fail" -gt 0 ] && exit 1
exit 0
